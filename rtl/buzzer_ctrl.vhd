-- ============================================================================
--  buzzer_ctrl  --  提示音效 / 音乐播放器（v2：整体升八度 + 预分频省面积）
--  Subsystem : S7 (sound output)
--  Improvement requirement A1 ("不同情况下播放不同的提示音效或音乐").
--
--  The board's buzzer is driven on PIN_60: writing a square wave in the audio
--  band makes it sound.  A "note" is therefore just a divider ratio, and the
--  real work is deciding WHICH note to play and FOR HOW LONG.
--
--  ---------------------------------------------------------------------------
--  ⚠️ 2026-10-09 第 14 工作阶段（用户实机反馈"游戏过程中完全没有声音"）：
--     旧版音域 **G4..C6（392..1047 Hz）**，而小板载蜂鸣器（压电/电磁换能器）
--     的谐振点通常在 **1~4 kHz** —— 392 Hz 处几乎推不动，实机就是"没声音"。
--     本轮做两件事（**架构不变，只改音高、位数与分频**）：
--
--     ① 音域整体上移一个八度以上：**C6..C7 = 1046.5..2093 Hz**
--        （既落在换能器高效区，也是芯片音乐（chiptune）的常用音域）。
--     ② 更省面积（旧版 68 LE，器件 100% 满 1260/1270 LE）：
--        先把 50 MHz 板钟 **64 分频** → tick = 781.25 kHz，方波计数器只数 tick；
--        半周期 = round(390625 / f) 拍，最大 373 → 计数器 **9 位**（旧版 16 位），
--        比较器 / 计数器一起瘦一圈。这就是讲义"资源共享"里"先把时间基准做粗、
--        再让每个消耗资源的模块只数粗刻度"的做法。
--
--  ⚠️ 2026-10-09 第 16 工作阶段（用户第二轮上板反馈）：
--     ① **对局里不要再有"移动键"音效**（"上下左右不需要额外音效，只要背景音乐，
--        不然听起来很乱"）→ 见 game_fsm 的按键音效表：移动/选择/开始全部静音，
--        只留"确认（锁定）"和"旋转"两个低频且有意义的反馈音；
--     ② **曲子/胜负音效要往"超级马里奥"那个水平靠** →
--        · 第一关 BGM = **Overworld 主题开头**（E E - E - C E - | G - - - G - - -）
--        · 第二关 BGM = **Underground（地下关）主题开头**（C C A A A# A#）
--        · 第三关 BGM = **Overworld 主题第二乐句**（C - - G - - E - | - A - B - A# A -）
--        · 预览/倒计时 = **马里奥金币音效**（B5 -> E6 上行四度）
--        · 通关胜利 = **过关号角（Course Clear）写法**：上行大三和弦琶音 ×2 + 下行收束
--        · 失败 = **Game Over 写法**：三声下行 + 下行小尾句，停在最低音
--        这些都是**通行转录的级数与节奏**（不是我随手编的），并且只保留了旋律，
--        没有使用任何原曲的录音/采样；本工程是课程作业，性质与非商业的
--        Arduino 蜂鸣器曲目集一致。
--     ③ **乐句从 8 步加长到 16 步**（2 s → **4 s 一循环**）：这是"曲子好不好听"的
--        关键 —— 8 步只够半个动机，听起来就是反复念半句。
--     ⚠️ 面积账（器件真正的瓶颈是 **127 个 LAB**，不是 1270 个 LE）：
--        16 步让"码+步"的查表输入变成 8 位，8 位函数要 **3 个 LUT4/输出位**（7 位只要 2 个）
--        → 旋律表 +4 LE；同时把预分频 ÷64→÷128→**÷256**、半周期计数器 9→**8 位**，
--        省回 ~2 LE（代价：音准最大偏 1.2%，见下面的音高表注释）；再删掉三个
--        已不再生成的码（1101/1110/1111）的查表分支。
--        ⚠️ 最终读数（收尾复核）：**1264 LE / 127 LAB（SEED 5）**；上面那条 1269 LE / SEED 11 是
--        **第一轮**（照抄休止的版本）的数 —— 第二轮连奏填音后旋律表可合并项变多，反而省了 5 LE。
--
--  音高表（8 个音，idx / 音名 / 目标频率 / 半周期拍数，f = 195312.5 / (2*(half+1))）：
--     0 E5  659.3->148   2 A5  880.0->111   4 B5   987.8-> 99   6 E6 1318.5->74
--     1 G5  784.0->125   3 A#5 932.3->105   5 C6  1046.5-> 93   7 G6 1568.0->62
--
--  音效码（4 位，game_fsm 发出；每句 **16 步 x 250 ms = 4 s**，步 0..15 循环）：
--     0000  静音（待机）
--     0001  自检 = POST 单声短鸣（C6 ≈1 kHz；第 0/8 步各一声。
--            ✅ ERR-051 已修：窗口恒为 8 步 ⇒ **两条进入路径都恰好一声**，
--            见下面 MEL_SELF 的注释）
--     0010  预览 = 马里奥金币音效        B5 E6 - - - - - - （每句两次）
--     0011  过关（大三和弦琶音回旋 ×2）  C6 E6 G6 E6 ...
--     0100  拼错（下行 + 低音抖动 ×2）   C6 B5 A#5 A5 G5 E5 ...
--     0101  按键（高音 blip；仅"开始"以外的保留码使用）
--     0110  通关胜利 = 过关号角          C6 E6 G6 - C6 E6 G6 - G6 E6 C6 C6
--     0111  失败 = Game Over             C6 G5 E5 - A5 B5 A5 A#5 G5 E5 A5 G5 E5
--     1000  **第一关 BGM** 马里奥 Overworld 开头
--     1001  **第二关 BGM** 马里奥 Underground 开头
--     1010  旋转 90°（逐级上行 ×2）      E5 G5 A5 A#5 B5 C6 E6 G6 ×2
--     1011  **第三关 BGM** 马里奥 Overworld 第二乐句
--           ⚠️ 三个 BGM 码必须正好是 `"10" & lvl3 & level` 的值（1000/1001/1011），
--              这样 game_fsm 那边是**纯拼线、0 逻辑单元**。
--     1100  确认 / 锁定（G6/C6 交替）
--     1101 / 1110 / 1111  预留（第 16 工作阶段起不再生成，查表落入 `when others` → 静音）
--  旋律写在常量表 MEL_* 里（每步 **4 位** = 1 位"这步响不响" + 3 位音高索引），
--  换旋律只改表、不碰逻辑：8 个音高共用**一个**方波发生器，
--  16 步节奏共用**一个**步进计数器。
--
--  ---------------------------------------------------------------------------
--  ⚠️ 面积实测（2026-10-09 第 14 工作阶段；**整机** `quartus_map` 层次表口径，
--     即 `docs/05` §1.1 记"旧版 68"的同一口径）：
--         旧版 buzzer_ctrl **68 LC / 24 寄存器**  →  本版 **57 LC / 23 寄存器**（−11，−16%）
--     拆开看（单模块消融实测）：预分频 + 9 位半周期计数器把"方波那一侧"从 63 降到 49，
--     但旋律表由 7 句扩到 16 句要多花 17（128x4 的查表在 4 输入 LUT 上就是这么贵）。
--     ⚠️ 若用**单模块顶层**的隔离仿真工程量，会得到 81 → 84（变大）—— 跨模块资源共享
--     只在整机里生效（`AUTO_RESOURCE_SHARING`），所以看面积**必须**用整机
--     `quartus/output_files/puzzle.map.rpt` 的层次表，口径要一致。
--
--  节拍用 **i_t4 = 4 Hz（250 ms）**：一次换一个音，一句 **16 步 = 4 s** 循环。
--  ⚠️ 早先这里写"2 s 一句"，那是 8 步时代的旧账（第 16 工作阶段加长到 16 步后已改）。
-- ============================================================================

library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity buzzer_ctrl is
    port (
        i_clk  : in  std_logic;                      -- 50 MHz
        i_rst  : in  std_logic;                      -- active HIGH
        i_en   : in  std_logic;                      -- '0' = force silence (SW7)
        i_sel  : in  std_logic_vector(3 downto 0);   -- sound code（本轮由 3 位加宽到 4 位）
        i_t4   : in  std_logic;                      -- 4 Hz tick (250 ms)：一步一个音
        o_buzz : out std_logic
    );
end entity buzzer_ctrl;

architecture rtl of buzzer_ctrl is

    ----------------------------------------------------------------------------
    -- 50 MHz / **256** = **195.3125 kHz** 的时间基准（tick）。
    -- ⚠️ 2026-10-09 第 16 工作阶段：预分频从 ÷64 → ÷128 → **÷256**，一路换来的是
    --    "音域下移一个八度"+"半周期计数器从 9 位缩到 **8 位**"：
    --      ÷256 后 E5(659 Hz) 只要 148 拍，8 位计数器（最大 255）够用，
    --      于是 `cnt` 少 1 位、`half` 多路器少 1 位、相等比较器少 1 位 ≈ **−2 LE**，
    --      代价只有预分频计数器多 1 位 —— 正好抵消"16 步乐句"多花的查表逻辑。
    --    代价是**音准**：tick 变粗后每个半周期的取整误差最大 1.2%
    --    （整首曲子会统一低 ~1% ≈ 1/6 个半音，音程关系不受影响，因此"听得出是哪首"
    --      完全保留）。这是本轮明确接受的一处"音质换面积"的取舍。
    ----------------------------------------------------------------------------
    constant PRE_DIV : integer := 256;

    ----------------------------------------------------------------------------
    -- 8 个音高的半周期（单位：**预分频后的 tick 数**，f = 195312.5 / (2*(half+1))）
    --
    -- ⚠️ 这 8 个音不是音阶而是**为几首曲子挑的**：把它们移调到同一主音后，
    --    超级马里奥的 Overworld 主题（两个乐句）、Underground 主题、以及
    --    过关号角/Game Over 句子所需的音**正好落在这 8 个音里**
    --    （= C 大调 E4..G5 那 8 个音升八度）。所以音高索引仍是 **3 位**。
    --
    --    idx 0 E5  659.3 -> 148     idx 4 B5  987.8 ->  99
    --    idx 1 G5  784.0 -> 125     idx 5 C6 1046.5 ->  93
    --    idx 2 A5  880.0 -> 111     idx 6 E6 1318.5 ->  74
    --    idx 3 A#5 932.3 -> 105     idx 7 G6 1568.0 ->  62
    ----------------------------------------------------------------------------
    function note_half(n : std_logic_vector(2 downto 0))
        return unsigned is
        variable v : unsigned(7 downto 0);
    begin
        case n is
            when "000"  => v := to_unsigned(148, 8);   -- E5
            when "001"  => v := to_unsigned(125, 8);   -- G5
            when "010"  => v := to_unsigned(111, 8);   -- A5
            when "011"  => v := to_unsigned(105, 8);   -- A#5
            when "100"  => v := to_unsigned(99, 8);    -- B5
            when "101"  => v := to_unsigned(93, 8);    -- C6（≈1 kHz，POST 自检声）
            when "110"  => v := to_unsigned(74, 8);    -- E6
            when others => v := to_unsigned(62, 8);    -- G6
        end case;
        return v;
    end function;

    -- one melody = **16 steps** (4 s), each 4 bits = bit3 = 响不响, bits 2..0 = 音高索引
    -- 音高索引：0 E5  1 G5  2 A5  3 A#5  4 B5  5 C6  6 E6  7 G6
    -- ⚠️ 第 16 工作阶段：一句从 8 步（2 s）加长到 **16 步（4 s）**。代价不是 0：
    --    查表输入从 4+3=**7 位**变成 4+4=**8 位**，而一个 LUT4 只有 4 个输入 ——
    --    7 位函数用"2 个 LUT4"就能实现（4 输入一级 + 剩下 3 位与中间结果再一级），
    --    **8 位函数每输出位要 3 个 LUT4**（两半各自一级、再合并），所以旋律表实测
    --    **+4 LE**（第 16 工作阶段按整机综合报告核对；本注释早先错写成"两者都只要
    --    2 个"，已按实测改正）。这 4 LE 由"预分频 ÷256 + 半周期计数器 9→8 位"
    --    （−2 LE）与"删掉三个不再生成的码的查表分支"换回来。
    --    换来的是**一句能装下一整个乐句**而不是半个动机 —— 用户说"曲子不够好"
    --    的第一个原因。
    -- ⚠️ **瞬时事件**（0011/0100/0101/1010/1100）的乐句必须 16 步全发声：
    --    它们只被保持 2 个旋律步，step 又是自由走的，落在休止上就等于"按了没反应"。
    type mel_t is array (0 to 15) of std_logic_vector(3 downto 0);

    -- 0000 静音（idle）
    constant MEL_SILENT : mel_t := ("0000", "0000", "0000", "0000",
                                    "0000", "0000", "0000", "0000",
                                    "0000", "0000", "0000", "0000",
                                    "0000", "0000", "0000", "0000");
    -- 0001 自检 = **行业标准的 POST 单声短鸣**："一短声 = 自检通过"（PC/工控惯例）。
    --      第 0 步和第 8 步各放一声（C6 ≈1 kHz）。
    --      ✅ **ERR-051 已修（2026-10-10，改的是 game_fsm 而不是这里）**：原来 `game_fsm`
    --        用"数 2 个 tick_1hz"当 2 s，入口相位不同实际只有 **(1,2] s = 4~8 步**，
    --        而 `step` 是自由走的 ⇒ **某些相位下这个 4~8 步的窗口一个发声步都碰不到，
    --        整段 2 s 一声不响**（"恰好一声"只在复位路径成立）。
    --        现在 `game_fsm` 改成数 **8 个 tick_4hz**（= 恰好 2 s，两条进入路径一致），
    --        窗口**恒为 8 个旋律步**；而 8 个连续步**必然恰好包含第 0 或第 8 步中的一个**
    --        （两者相隔 8）⇒ **恒为一声**，复位路径与 SW7 重新进入路径都一样。
    --        ⚠️ 本模块**一个字节都没改**（发声步仍是 0/8）—— 修的是"窗口长度不定"，
    --           不是"发声步选得不好"。证据：tb_game_fsm 的 SW7 重新进入断言 +
    --           tb_puzzle_top 的整机音效断言。
    constant MEL_SELF   : mel_t := ("1101", "0000", "0000", "0000",
                                    "0000", "0000", "0000", "0000",
                                    "1101", "0000", "0000", "0000",
                                    "0000", "0000", "0000", "0000");
    -- 0010 预览 / 倒计时 = **《塞尔达传说》"取得道具"音**（A5 A#5 B5 C6，四个半音级进上行 ×2）。
    --      ⚠️ 第 18 工作阶段（本轮）从"马里奥金币音（B5→E6 两音）"换成这一句，理由是
    --        用户反馈"区分度不够"，而**金币音只有 2 个音、且和胜利号角的起手都在高音区**，
    --        容易被混。这一句用了**全系统唯一的四连半音簇 A5 A#5 B5 C6**：
    --        查表里的音级集合是 {C,E,G,A,A#,B}，其中 A-A#-B-C 是全集合里**唯一的
    --        连续半音簇** —— 拿它做"获得/提示"是这套音里最有辨识度的素材，
    --        而且在 1~4 kHz 蜂鸣器谐振带里响度也好。
    --      ⚠️ 素材来源：Zelda "Item Get"（近藤浩治，1986）的通行旋律转录，只保留旋律、
    --        不用任何录音/采样；非商业课程作业，**不声称原创**（与三关 BGM 同一口径）。
    constant MEL_PREV   : mel_t := ("1010", "1011", "1100", "1101",
                                    "0000", "0000", "0000", "0000",
                                    "1010", "1011", "1100", "1101",
                                    "0000", "0000", "0000", "0000");
    -- 0011 过关（**瞬时事件** → 16 步全发声）：C6 E6 G6 E6 上行琶音回旋 ×2
    --      （大三和弦琶音 = 通用的"通过/得分"语汇，任何起始步都朝上）
    constant MEL_CLEAR  : mel_t := ("1101", "1110", "1111", "1110",
                                    "1101", "1110", "1111", "1110",
                                    "1101", "1110", "1111", "1110",
                                    "1101", "1110", "1111", "1110");
    -- 0100 拼错（**瞬时事件** → 16 步全发声）：E6 起**纯下行** + 低音抖动 ×2
    --      （E6 C6 B5 A#5 A5 G5 E5 G5）
    --      ⚠️ 第 18 工作阶段：起音由原来的 **C6 抬到 E6**，让它与
    --        「失败 Game Over」的起音（A#5）和「过关」的起音（C6）都不撞车 ——
    --        "共享起音是已证实的混淆源"（见 MEL_PREV 的说明）。
    constant MEL_WRONG  : mel_t := ("1110", "1101", "1100", "1011",
                                    "1010", "1001", "1000", "1001",
                                    "1110", "1101", "1100", "1011",
                                    "1010", "1001", "1000", "1001");
    -- 0101 按键（**瞬时事件** → 16 步全发声）：G6 高音短促 blip
    constant MEL_KEY    : mel_t := ("1111", "1111", "1111", "1111",
                                    "1111", "1111", "1111", "1111",
                                    "1111", "1111", "1111", "1111",
                                    "1111", "1111", "1111", "1111");
    -- 0110 **通关胜利 = 《最终幻想》"胜利号角"主题句**（B5 B5 B5 B5 | G5 A5 B5 A5 B5，收在主音 B5 上拖长）。
    --      ⚠️ 第 18 工作阶段（本轮）换素材：原来用的是马里奥"过关号角（Course Clear）"的写法，
    --        用户反馈"胜利音效区分度不够"。换成 FF 胜利号角的原因：
    --          ① 它是**同音反复起手**（B5×4）—— 与三关 BGM 全部是"级进/波浪"起手形成对比；
    --          ② 它的**收束长音落在 B5**，而失败句落在最低音 E5，一高一低、方向相反；
    --          ③ 它是游戏史上最"正统"的过关号角，氛围感最强。
    --      ⚠️ 为什么不用原曲的完整三句：那需要 F#/D 等音，而本播放器只有
    --        {C,E,G,A,A#,B} 这 6 个音级 —— **原曲后半句结构上放不进来**
    --        （详见 docs/06 §19 的"哪些名曲塞不进这 8 个音"）。
    --        这里用的是**能 1:1 落进音集的主题句**（B5 B5 B5 B5 G5 A5 B5 A5 B5）。
    --      ⚠️ 末尾 2 步留白：号角"吹完就静下来"，与失败句的句尾留白同一处理。
    constant MEL_WIN    : mel_t := ("1100", "1100", "1100", "1100",
                                    "1001", "1010", "1100", "1010",
                                    "1100", "1100", "1100", "1100",
                                    "1100", "1100", "0000", "0000");
    -- 0111 **失败 = Game Over：A#5 → A5 → G5 → E5 的稀疏纯下行**，停在最低音。
    --      ⚠️ 第 18 工作阶段（本轮）**改成"稀疏"**（4 个音 + 大量留白），目的是拉开区分度：
    --        人因工程的成熟做法是"**用不同的音符数与节奏型编码不同含义**"
    --        （消防 T-3/T-4 靠脉冲数区分；IEC 60601-1-8 2020 改版用 1/3/10 个音表示
    --         低/中/高紧迫度）—— 而"音高本身"是最弱的区分维度。
    --        于是本轮的 6 个主要音效各占一个"音符数"：自检 1、失败 4、第二关 BGM 6、
    --        第三关 BGM 9、胜利 14、第一关 BGM 16。
    --      ⚠️ **A#5 是这套 8 音里唯一的"集合外半音"**（音级集合 {C,E,G,A,A#,B}），
    --        所以把它独占给"失败"当**语义路标**：听到 A#5 起手 = 输了。
    --      ⚠️ 句尾 6 步留白是**刻意的**（"Game Over 说完就该静下来"）。
    constant MEL_FAIL   : mel_t := ("1011", "0000", "0000", "1010",
                                    "0000", "0000", "1001", "0000",
                                    "0000", "1000", "0000", "0000",
                                    "0000", "0000", "0000", "0000");
    -- 1000 **第一关 BGM = 超级马里奥 Overworld 主题开头**（全世界最有名的游戏 BGM）：
    --      原谱 E5 E5 - E5 - C5 E5 - | G5 - - - G4 - - -
