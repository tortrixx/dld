    --         休止**（16 步里只有 7 步发声 = 56% 是静音），小蜂鸣器上听起来就是"滴滴滴
    --         停顿停顿"，所以现在把每个休止**用"下一个要响的音"补上**（连奏/legato
    --         填音）：音高序列与音的顺序一个不变（所以还听得出是马里奥），
    --         但**16 步全部发声**，变成一条连绵的旋律线。
    --      实际发声：E6 E6 E6 E6 | C6 C6 E6 G6 | G6 G5 G5 G5 | G5 G5 G5 G5
    constant MEL_BGM1   : mel_t := ("1110", "1110", "1110", "1110",
                                    "1101", "1101", "1110", "1111",
                                    "1111", "1001", "1001", "1001",
                                    "1001", "1001", "1001", "1001");
    -- 1001 **第二关 BGM = 低音区、稀疏脉冲的暗色动机**（E5 与 G5 的窄幅摇摆，6 个音）。
    --      ⚠️ 第 18 工作阶段（本轮）从"马里奥 Underground 开头（C6 C6 A5 A5 A#5 A#5…）"
    --        换成这一句，理由是用户反馈三关 BGM **区分度不够**。原来三首全在
    --        C6~G6 一带、且都是"每步一音"的连奏，听起来像同一首曲子的三段。
    --        本轮的分配原则来自听觉告警/耳标设计的三条实证结论：
    --          ① **音区只做"粗分"**（同一音区内不要再靠 1~2 个半音区分）；
