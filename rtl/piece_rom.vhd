-- ============================================================================
--  piece_rom  --  零片形状查找表
--  子系统：S5（图案与随机数据）
--
--  纯组合逻辑。一次返回全部四块零片形状（而不是「给我第 k 号形状」）：
--  引擎每一帧本来就需要全部形状，而一起返回
--  意味着引擎内部永远不必把该 ROM 实例化
--  四次 —— 那会在 puzzle_ctrl 里塞进一个隐藏模块，
--  破坏「系统框图与代码一致」这条规则。
--
--  第一关形状来自图 4-2，逐像素精确解码：3 + 6 + 3 = 12
--  格，与 12 格的图 4-1 图案面积守恒。
--  第二关**与第三关**使用同一套四块自行设计的异形零片
--  （3 + 2 + 5 + 6 = 16 格，2026-10-09 第 11 工作阶段；在那之前它们是
--  四块相同的 2x2 方块 —— 见 rtl/puzzle_pkg.vhd L2_P0..P3 与 docs/02 §9.2）。
--  ⚠️ 第 12 工作阶段（D2）把游戏变成三关：**第三关沿用同一套四块异形零片**，
--     所以这里仍然是"两级分支"（i_level='0' = 第一关三块；'1' = 第二/三关四块）。
--
--  所有形状都装进 3x3 的包围盒（常量 PIECE_MAX_DIM），正因如此
--  引擎只需扫描 3x3 邻域，而不必扫描整块面板。
-- ============================================================================

library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use work.puzzle_pkg.ALL;

entity piece_rom is
    port (
        i_level : in  std_logic;                      -- '0' = 第一关，'1' = 第二/三关
        o_mask  : out mask_arr_t;                     -- 4 个相对形状掩码
        o_h     : out dim_arr_t;                      -- 4 个包围盒高度
        o_w     : out dim_arr_t;                      -- 4 个包围盒宽度
        o_n     : out std_logic_vector(2 downto 0)    -- 本关使用多少块零片
    );
end entity piece_rom;

architecture rtl of piece_rom is
begin

    process (i_level)
    begin
        if (i_level = '0') then
            -- ---------------- 第一关：3 块零片（第 3 槽未使用） -------------
            o_mask <= (L1_P0, L1_P1, L1_P2, MASK_ZERO);
            o_h    <= ("001", "011", "010", "000");   -- 1, 3, 2, -
            o_w    <= ("011", "011", "010", "000");   -- 3, 3, 2, -
            o_n    <= "011";                          -- 3
        else
            -- ---------------- 第二/三关：4 块零片（自行设计，2026-10-09） -----
            --   Q0 1x3 长条（3）/ Q1 1x2 双连格（2）/ Q2 J 形五连方（5）/
            --   Q3 六格块（6）= 16 格，每块只有一个朝向（不旋转）。
            --   scripts/check_geometry.py 穷举每一幅图案被这四块形状
            --   精确平移铺满的所有方案（第二关固定 PAT3、第三关四幅随机）。
            o_mask <= (L2_P0, L2_P1, L2_P2, L2_P3);
            o_h    <= ("001", "010", "011", "011");   -- 1, 2, 3, 3
            o_w    <= ("011", "001", "011", "011");   -- 3, 1, 3, 3
            o_n    <= "100";                          -- 4
        end if;
    end process;

end architecture rtl;
