-- ============================================================================
--  piece_rom  ——  零片形状查找表
--  所属子系统：S5（图案与随机数据）
--
--  纯组合逻辑，没有寄存器。
--
--  一次返回全部四块零片的形状，而不是"给出第 k 号形状"：引擎每一帧
--  本来就需要全部形状；集中返回可以避免在 puzzle_ctrl 内部再实例化
--  四个 ROM，保持"系统框图与代码一一对应"。
--
--  第一关：图 4-2 的三块零片，3 + 6 + 3 = 12 格，与图 4-1 的 12 格面积守恒。
--  第二 / 三关：同一套四块自拟异形零片，3 + 2 + 5 + 6 = 16 格。
--  所有形状都装在 3x3 包围盒内（PIECE_MAX_DIM），因此引擎只需扫描
--  3x3 邻域，不必扫描整块面板。
-- ============================================================================

library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use work.puzzle_pkg.ALL;

entity piece_rom is
    port (
        i_level : in  std_logic;                      -- '0' = 第一关，'1' = 第二/三关
        o_mask  : out mask_arr_t;                     -- 4 个相对形状掩码
        o_h     : out dim_arr_t;                      -- 4 个包围盒高度
        o_w     : out dim_arr_t;                      -- 4 个包围盒宽度
        o_n     : out std_logic_vector(2 downto 0)    -- 本关使用多少块零片
    );
end entity piece_rom;

architecture rtl of piece_rom is
begin

    process (i_level)
    begin
        if (i_level = '0') then
            -- ---------------- 第一关：3 块零片（第 3 槽未使用） -------------
            o_mask <= (L1_P0, L1_P1, L1_P2, MASK_ZERO);
            o_h    <= ("001", "011", "010", "000");   -- 1, 3, 2, -
            o_w    <= ("011", "011", "010", "000");   -- 3, 3, 2, -
            o_n    <= "011";                          -- 3
        else
            -- ---------------- 第二 / 三关：4 块自拟零片 -------------
            -- Q0 1x3 长条（3）/ Q1 1x2 竖条（2）/
            -- Q2 J 形五连方（5）/ Q3 六格块（6），共 16 格。
            -- 四幅图案都能被这四块形状恰好铺满。
            o_mask <= (L2_P0, L2_P1, L2_P2, L2_P3);
            o_h    <= ("001", "010", "011", "011");   -- 1, 2, 3, 3
            o_w    <= ("011", "001", "011", "011");   -- 3, 1, 3, 3
            o_n    <= "100";                          -- 4
        end if;
    end process;

end architecture rtl;
